/**
 * Regenerates data/informational-index.generated.ts: a slug -> lazy dynamic-import map
 * for every pure informational guide data file under data/informational-guides/*.ts.
 *
 * Mirrors scripts/generate-guides-index.mjs but for the separate informational-guide
 * pipeline (components/guide/InformationalGuidePage.tsx) — no products, no scoring,
 * no Check Price CTAs. Must be re-run any time a data/informational-guides/<slug>.ts
 * file is added or removed.
 *
 * Usage: node scripts/generate-informational-index.mjs
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const GUIDES_DIR = resolve(ROOT, "data", "informational-guides");

const REQUIRED_EXPORTS = ["title", "metaTitle", "metaDescription", "bodyHtml", "toc", "relatedGuides"];

const allSlugs = existsSync(GUIDES_DIR)
  ? readdirSync(GUIDES_DIR)
      .filter((f) => f.endsWith(".ts"))
      .map((f) => f.replace(/\.ts$/, ""))
      .sort()
  : [];

const slugs = [];
const skipped = [];
for (const slug of allSlugs) {
  const content = readFileSync(resolve(GUIDES_DIR, `${slug}.ts`), "utf8");
  const missing = REQUIRED_EXPORTS.filter((name) => !new RegExp(`export const ${name}\\b`).test(content));
  if (missing.length > 0) {
    skipped.push(slug);
  } else {
    slugs.push(slug);
  }
}

const entries = slugs
  .map((slug) => `  ${JSON.stringify(slug)}: () => import("./informational-guides/${slug}"),`)
  .join("\n");

const content = `// AUTO-GENERATED by scripts/generate-informational-index.mjs - do not hand-edit.
// Re-run that script after adding or removing any data/informational-guides/<slug>.ts file.

export interface InformationalGuideModule {
  slug: string;
  title: string;
  metaTitle: string;
  metaDescription: string;
  author: string;
  datePublished: string;
  readTime: string;
  cluster: string;
  heroImage: string;
  heroImageAlt: string;
  bodyHtml: string;
  toc: { id: string; text: string; level: 2 | 3 }[];
  relatedGuides: { href: string; title?: string }[];
}

export const informationalGuideLoaders: Record<string, () => Promise<InformationalGuideModule>> = {
${entries}
};
`;

writeFileSync(resolve(ROOT, "data", "informational-index.generated.ts"), content, "utf8");
console.log(`Wrote data/informational-index.generated.ts with ${slugs.length} entries (${skipped.length} skipped).`);
if (skipped.length) console.log("Skipped:", skipped.join(", "));
